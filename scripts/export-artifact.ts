import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./lib/secrets.js";

/** Copy the compiled ledger ABI and bytecode into the core package so the app and scripts never hand-maintain an ABI. Run after `forge build`. */
const art = JSON.parse(readFileSync(join(ROOT, "contracts", "out", "TravelRuleLedger.sol", "TravelRuleLedger.json"), "utf8"));
const out = `// Generated by scripts/export-artifact.ts from contracts/out. Do not edit.
export const ledgerAbi = ${JSON.stringify(art.abi, null, 2)} as const;
export const ledgerBytecode = ${JSON.stringify(art.bytecode.object)} as \`0x\${string}\`;
`;
writeFileSync(join(ROOT, "packages", "core", "src", "generated", "ledger.ts"), out);
console.log(`exported ${art.abi.length} ABI entries, ${(art.bytecode.object.length - 2) / 2} bytes of bytecode`);
